func normalizeFields(kv ...any) map[string]any {
	if len(kv) == 0 {
		return nil
	}
	fields := make(map[string]any, (len(kv)+1)/2)
	for i := 0; i < len(kv); i += 2 {
		if i+1 >= len(kv) {
			fields["!BADKEY"] = normalizeFieldValue(kv[i])
			break
		}
		var key string
		if s, ok := kv[i].(string); ok {
			key = s
		} else {
			key = fmt.Sprint(kv[i])
		}
		fields[key] = normalizeFieldValue(kv[i+1])
	}
	return fields
}

func normalizeFieldValue(v any) any {
	return normalizeFieldValueDepth(v, 0)
}

func normalizeFieldValueDepth(v any, depth int) any {
	if v == nil {
		return nil
	}
	if depth >= maxFieldNormalizeDepth {
		return "[max-depth]"
	}
	switch val := v.(type) {
	case string, bool,
		int, int8, int16, int32, int64,
		uint, uint8, uint16, uint32, uint64, uintptr:
		return val
	case float64:
		if math.IsNaN(val) || math.IsInf(val, 0) {
			return fmt.Sprint(val)
		}
		return val
	case float32:
		if math.IsNaN(float64(val)) || math.IsInf(float64(val), 0) {
			return fmt.Sprint(val)
		}
		return val
	case error:
		if isNilValue(val) {
			return nil
		}
		return val.Error()
	case []any:
		out := make([]any, len(val))
		for i, item := range val {
			out[i] = normalizeFieldValueDepth(item, depth+1)
		}
		return out
	case map[string]any:
		out := make(map[string]any, len(val))
		for k, item := range val {
			out[k] = normalizeFieldValueDepth(item, depth+1)
		}
		return out
	}

	rv := reflect.ValueOf(v)
	switch rv.Kind() {
	case reflect.Func, reflect.Chan, reflect.Complex64, reflect.Complex128, reflect.UnsafePointer:
		return fmt.Sprint(v)
	case reflect.Pointer:
		if rv.IsNil() {
			return nil
		}
	}

	if _, err := json.Marshal(v); err != nil {
		if strings.Contains(err.Error(), "cycle") {
			return fmt.Sprintf("<cyclic %T>", v)
		}
		return fmt.Sprint(v)
	}
	return v
}

func isNilValue(v any) bool {
	rv := reflect.ValueOf(v)
	switch rv.Kind() {
	case reflect.Pointer, reflect.Interface, reflect.Map, reflect.Slice, reflect.Chan, reflect.Func:
		return rv.IsNil()
	default:
		return false
	}
}

func formatSortedFields(fields map[string]any) string {
	if len(fields) == 0 {
		return ""
	}
	keys := make([]string, 0, len(fields))
	for k := range fields {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var b strings.Builder
	for i, k := range keys {
		if i > 0 {
			b.WriteByte(' ')
		}
		b.WriteString(k)
		b.WriteByte('=')
		fmt.Fprint(&b, fields[k])
	}
	return b.String()
}
