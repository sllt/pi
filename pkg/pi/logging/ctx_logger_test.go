package logging

import (
	"bytes"
	"context"
	"encoding/json"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
	"go.opentelemetry.io/otel/trace"
)

type embeddedCtxHolder struct {
	ContextLogger
}

func TestContextLogger_UpdateContextAndAutogeneratedCallerSkip(t *testing.T) {
	var buf bytes.Buffer
	base := NewWriterLogger(DEBUG, &buf, &buf)
	if cc, ok := base.(CallerConfigurer); ok {
		cc.SetShowCaller(true)
	}

	tid1, err := trace.TraceIDFromHex("11111111111111111111111111111111")
	require.NoError(t, err)
	sid1, err := trace.SpanIDFromHex("2222222222222222")
	require.NoError(t, err)
	ctx1 := trace.ContextWithSpanContext(context.Background(), trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    tid1,
		SpanID:     sid1,
		TraceFlags: trace.FlagsSampled,
	}))

	holder := &embeddedCtxHolder{
		ContextLogger: *NewContextLogger(ctx1, base),
	}

	// Direct call on embedded *ContextLogger
	holder.Infof("hello %s", "first")

	// UpdateContext switches active Span TraceID dynamically
	tid2, err := trace.TraceIDFromHex("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa")
	require.NoError(t, err)
	ctx2 := trace.ContextWithSpanContext(context.Background(), trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    tid2,
		SpanID:     sid1,
		TraceFlags: trace.FlagsSampled,
	}))
	holder.UpdateContext(ctx2)

	// Interface dispatch through value-embedded struct (<autogenerated> wrapper)
	var asInterface Logger = holder
	asInterface.Infof("hello %s", "second")

	lines := bytes.Split(bytes.TrimSpace(buf.Bytes()), []byte("\n"))
	require.Len(t, lines, 2)

	type parsedLog struct {
		Caller  string `json:"caller"`
		TraceID string `json:"trace_id"`
	}
	var first, second parsedLog
	require.NoError(t, json.Unmarshal(lines[0], &first))
	require.NoError(t, json.Unmarshal(lines[1], &second))

	assert.Equal(t, tid1.String(), first.TraceID)
	assert.Contains(t, first.Caller, "ctx_logger_test.go:")
	assert.NotContains(t, first.Caller, "<autogenerated>")

	assert.Equal(t, tid2.String(), second.TraceID)
	assert.Contains(t, second.Caller, "ctx_logger_test.go:")
	assert.NotContains(t, second.Caller, "<autogenerated>")
}

func TestContextLogger_ZeroValueAndNilSafety(t *testing.T) {
	var nilLogger *ContextLogger
	require.NotPanics(t, func() {
		nilLogger.UpdateContext(context.Background())
		nilLogger.Info("safe")
		nilLogger.Infof("safe %d", 1)
		nilLogger.ChangeLevel(ERROR)
	})

	zeroLogger := &ContextLogger{}
	require.NotPanics(t, func() {
		zeroLogger.UpdateContext(nil)
		zeroLogger.Info("safe")
		zeroLogger.Errorf("safe %d", 2)
		zeroLogger.ChangeLevel(DEBUG)
	})
}
