type embeddedCtxHolder struct {
	ContextLogger
}

type AppLogger struct {
	Logger
}

func TestContextLogger_UpdateContextAndAutogeneratedCallerSkip(t *testing.T) {
	var buf bytes.Buffer
	base := NewWriterLogger(DEBUG, &buf, &buf)
	if cc, ok := base.(CallerConfigurer); ok {
		cc.SetShowCaller(true)
	}

	tid1, err := trace.TraceIDFromHex("11111111111111111111111111111111")
	require.NoError(t, err)
	sid1, err := trace.SpanIDFromHex("2222222222222222")
	require.NoError(t, err)
	ctx1 := trace.ContextWithSpanContext(context.Background(), trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    tid1,
		SpanID:     sid1,
		TraceFlags: trace.FlagsSampled,
	}))

	holder := &embeddedCtxHolder{
		ContextLogger: *NewContextLogger(ctx1, base),
	}

	// Direct call on embedded *ContextLogger
	holder.Infof("hello %s", "first")

	// UpdateContext switches active Span TraceID dynamically
	tid2, err := trace.TraceIDFromHex("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa")
	require.NoError(t, err)
	ctx2 := trace.ContextWithSpanContext(context.Background(), trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    tid2,
		SpanID:     sid1,
		TraceFlags: trace.FlagsSampled,
	}))
	holder.UpdateContext(ctx2)

	// Interface dispatch through value-embedded struct (<autogenerated> wrapper)
	var asInterface Logger = holder
	asInterface.Infof("hello %s", "second")

	lines := bytes.Split(bytes.TrimSpace(buf.Bytes()), []byte("\n"))
	require.Len(t, lines, 2)

	type parsedLog struct {
		Caller  string `json:"caller"`
		TraceID string `json:"trace_id"`
	}
	var first, second parsedLog
	require.NoError(t, json.Unmarshal(lines[0], &first))
	require.NoError(t, json.Unmarshal(lines[1], &second))

	assert.Equal(t, tid1.String(), first.TraceID)
	assert.Contains(t, first.Caller, "ctx_logger_test.go:")
	assert.NotContains(t, first.Caller, "<autogenerated>")

	assert.Equal(t, tid2.String(), second.TraceID)
	assert.Contains(t, second.Caller, "ctx_logger_test.go:")
	assert.NotContains(t, second.Caller, "<autogenerated>")
}

func TestContextLogger_ZeroValueAndNilSafety(t *testing.T) {
	var nilLogger *ContextLogger
	require.NotPanics(t, func() {
		nilLogger.UpdateContext(context.Background())
		nilLogger.Info("safe")
		nilLogger.Infof("safe %d", 1)
		nilLogger.ChangeLevel(ERROR)
	})

	zeroLogger := &ContextLogger{}
	require.NotPanics(t, func() {
		zeroLogger.UpdateContext(nil)
		zeroLogger.Info("safe")
		zeroLogger.Errorf("safe %d", 2)
		zeroLogger.ChangeLevel(DEBUG)
	})
}

func TestWithContext(t *testing.T) {
	tid1, err := trace.TraceIDFromHex("0123456789abcdef0123456789abcdef")
	require.NoError(t, err)
	sid1, err := trace.SpanIDFromHex("1111111111111111")
	require.NoError(t, err)
	ctx1 := trace.ContextWithSpanContext(context.Background(), trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    tid1,
		SpanID:     sid1,
		TraceFlags: trace.FlagsSampled,
	}))

	tid2, err := trace.TraceIDFromHex("fedcba9876543210fedcba9876543210")
	require.NoError(t, err)
	sid2, err := trace.SpanIDFromHex("2222222222222222")
	require.NoError(t, err)
	ctx2 := trace.ContextWithSpanContext(context.Background(), trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    tid2,
		SpanID:     sid2,
		TraceFlags: trace.FlagsSampled,
	}))

	t.Run("emits exact 32-hex trace_id", func(t *testing.T) {
		var buf bytes.Buffer
		base := NewWriterLogger(DEBUG, &buf, &buf)

		l := WithContext(ctx1, base)
		l.Infof("service event %d", 42)

		var entry struct {
			TraceID string `json:"trace_id"`
			Message string `json:"message"`
		}
		require.NoError(t, json.Unmarshal(bytes.TrimSpace(buf.Bytes()), &entry))
		assert.Equal(t, tid1.String(), entry.TraceID)
		assert.Len(t, entry.TraceID, 32)
		assert.Equal(t, "service event 42", entry.Message)
	})

	t.Run("nested WithContext unwraps base without double trace_id maps", func(t *testing.T) {
		var buf bytes.Buffer
		base := NewWriterLogger(DEBUG, &buf, &buf)

		l1 := WithContext(ctx1, base)
		l2 := WithContext(ctx2, l1)
		assert.Same(t, base, l2.base)

		l2.Info("nested", "extra")

		// Clearing span context on nested wrap must not leak outer trace_id.
		l3 := WithContext(context.Background(), l2)
		assert.Same(t, base, l3.base)
		l3.Info("untraced")

		lines := bytes.Split(bytes.TrimSpace(buf.Bytes()), []byte("\n"))
		require.Len(t, lines, 2)

		var second struct {
			TraceID string `json:"trace_id"`
			Message []any  `json:"message"`
		}
		require.NoError(t, json.Unmarshal(lines[0], &second))
		assert.Equal(t, tid2.String(), second.TraceID)
		assert.Equal(t, []any{"nested", "extra"}, second.Message)

		var third struct {
			TraceID string `json:"trace_id"`
			Message string `json:"message"`
		}
		require.NoError(t, json.Unmarshal(lines[1], &third))
		assert.Empty(t, third.TraceID)
		assert.Equal(t, "untraced", third.Message)
	})

	t.Run("nil ctx and nil base safety", func(t *testing.T) {
		var typedNil *ContextLogger
		require.NotPanics(t, func() {
			l1 := WithContext(nil, nil)
			l1.Info("noop")
			l1.ChangeLevel(WARN)

			l2 := WithContext(ctx1, nil)
			l2.Infof("noop %s", "x")

			l3 := WithContext(ctx1, typedNil)
			l3.Error("noop")

			var buf bytes.Buffer
			l4 := WithContext(nil, NewWriterLogger(DEBUG, &buf, &buf))
			l4.Info("plain")
			assert.Contains(t, buf.String(), `"plain"`)
			assert.NotContains(t, buf.String(), `"trace_id"`)
		})
	})

	t.Run("accurate caller file:line when wrapped in outer AppLogger struct", func(t *testing.T) {
		var buf bytes.Buffer
		base := NewWriterLogger(DEBUG, &buf, &buf)
		if cc, ok := base.(CallerConfigurer); ok {
			cc.SetShowCaller(true)
		}

		appLog := AppLogger{Logger: WithContext(ctx1, base)}
		_, _, lineBefore, ok := runtime.Caller(0)
		require.True(t, ok)
		appLog.Infof("wrapped %s", "call")

		var entry struct {
			Caller  string `json:"caller"`
			TraceID string `json:"trace_id"`
			Message string `json:"message"`
		}
		require.NoError(t, json.Unmarshal(bytes.TrimSpace(buf.Bytes()), &entry))
		assert.Equal(t, tid1.String(), entry.TraceID)
		assert.Equal(t, "wrapped call", entry.Message)
		assert.Equal(t, fmt.Sprintf("ctx_logger_test.go:%d", lineBefore+2), entry.Caller)
		assert.NotContains(t, entry.Caller, "<autogenerated>")
	})

	t.Run("WithContext wrapping MockLogger does not append trace map to args", func(t *testing.T) {
		logs := testutil.StdoutOutputForFunc(func() {
			mock := NewMockLogger(DEBUG)
			WithContext(ctx1, mock).Infof("hello %s", "world")
		})
		assert.Equal(t, "hello world\n", logs)
		assert.NotContains(t, logs, "EXTRA")
		assert.NotContains(t, logs, "__trace_id__")
	})

	t.Run("Noop returns singleton safe logger", func(t *testing.T) {
		n1 := Noop()
		n2 := Noop()
		require.NotNil(t, n1)
		assert.Equal(t, n1, n2)
		require.NotPanics(t, func() {
			n1.Debug("d")
			n1.Debugf("%s", "d")
			n1.Info("i")
			n1.Infof("%s", "i")
			n1.Notice("n")
			n1.Noticef("%s", "n")
			n1.Warn("w")
			n1.Warnf("%s", "w")
			n1.Error("e")
			n1.Errorf("%s", "e")
			n1.Fatal("f")
			n1.Fatalf("%s", "f")
			n1.Log("l")
			n1.Logf("%s", "l")
			n1.ChangeLevel(ERROR)
			WithContext(ctx1, n1).Infof("noop %s", "ctx")
		})
	})
}
